// ── Монотонные часы ───────────────────────────────────────────────────────────
//
// Миллисекунды с запуска процесса. Date.now() для измерения промежутков здесь
// не годится: у табло нет ни NTP, ни живого RTC, и системные часы подводит
// server/timeSync.js по времени из пакетов BCS_Loader. Каждый такой перевод
// мгновенно «состарил» бы живой поток данных (прыжок вперёд) или наоборот
// спрятал бы обрыв связи (прыжок назад) — ровно это и происходило: киоск
// моргал «нет данных» на ровном месте.

const { performance } = require('perf_hooks');

function now() { return performance.now(); }

module.exports = { now };
