'use strict';

// ── Отсев повторов посылки настроек ──────────────────────────────────────────
//
// Одна и та же посылка приходит на табло по нескольку раз, и по обоим каналам:
//   • RS-485 — Loader намеренно шлёт каждую настройку ConfigRepeat раз: линия
//     односторонняя, подтверждений нет, и потерянную часть добирает следующий
//     проход;
//   • TCP/IP — «Сохранить» повторяет запрос после таймаута, а таймаут на этой
//     сети случается и у запроса, который до табло всё-таки доехал.
//
// Применять одно и то же дважды незачем и вредно: saveIndicators переписывает
// список индикаторов целиком (меняются их id), киоск перестраивает раскладку
// и перезапускает видеопоток, в журнале это выглядит как два сохранения.
//
// Ключ отсева — вид посылки и её текст целиком. Loader кладёт в каждую посылку
// `sid` — номер отправки, — поэтому повторы одной отправки совпадают дословно,
// а новая отправка с тем же содержимым отличается и проходит. Для Loader без
// `sid` остаётся сравнение по содержимому: повтор отсеивается, но и
// намеренное повторное сохранение той же раскладки — тоже.
//
// Помним только последнюю применённую посылку: «вернуться к предыдущему»
// (профиль A → B → A) не должно отсеиваться, и не отсеивается.

const mono = require('./monotonic');

/// Окно отсева. Считаем монотонными часами: перевод системных (timeSync) не
/// должен ни пропускать повтор, ни держать отсев лишние минуты.
const DEFAULT_WINDOW_MS = 60000;

class ApplyGuard {
    constructor(opts) {
        opts = opts || {};
        this._window = opts.windowMs || DEFAULT_WINDOW_MS;
        this._now    = opts.now || mono.now;
        this._last   = { kind: null, json: null, at: -Infinity };
    }

    /// Это повтор уже применённой посылки? Окно скользящее: каждый отсеянный
    /// повтор отодвигает его. Длинная посылка идёт частями и повторяется
    /// проходами по многу секунд — без сдвига последний проход вышел бы за
    /// окно и применился заново.
    isRepeat(kind, data) {
        const json = _json(data);
        if (json === null) return false;
        if (this._last.kind !== kind || this._last.json !== json) return false;
        if ((this._now() - this._last.at) >= this._window) return false;
        this._last.at = this._now();
        return true;
    }

    /// Посылка применена — запомнить её как последнюю.
    applied(kind, data) {
        this._last = { kind: kind, json: _json(data), at: this._now() };
    }

    /// Применение не удалось: повтор нужен, отсев снимаем.
    failed() {
        this._last = { kind: null, json: null, at: -Infinity };
    }

    reset() { this.failed(); }
}

function _json(data) {
    try { return JSON.stringify(data); } catch (_) { return null; }
}

/// Табло одно, и «последняя применённая посылка» у него одна на оба канала:
/// повтор по TCP после отправки по линии — тот же повтор.
const shared = new ApplyGuard();

module.exports = { ApplyGuard, shared, DEFAULT_WINDOW_MS };
